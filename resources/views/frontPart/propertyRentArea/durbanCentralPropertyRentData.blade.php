<p>There is also plenty on offer in the city for sports lovers, including national and international cricket games at the Sahara Kingsmead stadium, rugby at the Growthpoint Kings Park stadium and soccer at the famous Moses Mabhida stadium that was built for the Soccer World Cup in 2010.</p>
